const box = (type: string, ...parts: Buffer[]) => { const body = Buffer.concat(parts); return Buffer.concat([u32(8 + body.length), latin(type), body]); };
const fullBox = (type: string, version: number, flags: number, ...parts: Buffer[]) => box(type, Buffer.from([version, (flags >> 16) & 255, (flags >> 8) & 255, flags & 255]), ...parts);
const C2PA_UUID = Buffer.from("d8fec3d61b0e483c92975828877ec481", "hex");

type TrackSpec = {
  handler: "vide" | "soun" | "meta"; samples: Buffer[]; wide: boolean;
  /** One stsc run per chunk instead of one run for all (the same layout, a much longer table). */
  runPerChunk?: boolean;
  /** Replaces the computed chunk offsets (given this track's and every track's). */
  offsets?: (own: number[], all: number[][]) => number[];
  /** Replace the stsz and stsc boxes. */
  stsz?: Buffer;
  stsc?: Buffer;
};
function sampleEntry(handler: TrackSpec["handler"]): Buffer {
  if (handler === "vide") {
    const name = Buffer.alloc(32); name[0] = VENDOR.length; name.write(VENDOR, 1, "latin1");
    return box("avc1", Buffer.alloc(6), u16(1), u16(0), u16(0), latin("vndr"), u32(512), u32(512), u16(PICTURE.width), u16(PICTURE.height),
      u32(0x00480000), u32(0x00480000), u32(0), u16(1), name, u16(0x18), Buffer.from([0xff, 0xff]), box("avcC", Buffer.from([1, 0x64, 0, 0x1f, 0xff, 0xe0])));
  }
  if (handler === "soun") return box("mp4a", Buffer.alloc(6), u16(1), u16(0), u16(0), latin("vndr"), u16(2), u16(16), u16(0), u16(0), u32(48000 << 16), box("esds", Buffer.alloc(4)));
  return box("mett", Buffer.alloc(6), u16(1), latin(`${VENDOR}\0`), latin("text/plain\0"));
}
function trakBox(spec: TrackSpec, id: number, computed: number[], all: number[][]): Buffer {
  const offsets = spec.offsets ? spec.offsets(computed, all) : computed;
  const stsc = spec.stsc ?? (spec.runPerChunk
    ? fullBox("stsc", 0, 0, u32(offsets.length), Buffer.concat(offsets.flatMap((_, i) => [u32(i + 1), u32(1), u32(1)])))
    : fullBox("stsc", 0, 0, u32(1), u32(1), u32(1), u32(1)));
  const header = spec.handler === "vide" ? fullBox("vmhd", 0, 1, Buffer.alloc(8)) : spec.handler === "soun" ? fullBox("smhd", 0, 0, Buffer.alloc(4)) : fullBox("nmhd", 0, 0);
  const stbl = box("stbl",
    fullBox("stsd", 0, 0, u32(1), sampleEntry(spec.handler)),
    fullBox("stts", 0, 0, u32(1), u32(spec.samples.length), u32(1000)),
    stsc,
    spec.stsz ?? fullBox("stsz", 0, 0, u32(0), u32(spec.samples.length), Buffer.concat(spec.samples.map((s) => u32(s.length)))),
    spec.wide ? fullBox("co64", 0, 0, u32(offsets.length), Buffer.concat(offsets.map(u64))) : fullBox("stco", 0, 0, u32(offsets.length), Buffer.concat(offsets.map(u32))),
  );
  return box("trak",
    fullBox("tkhd", 0, 3, u32(3_900_000_000), u32(3_900_000_001), u32(id), u32(0), u32(3000), Buffer.alloc(8), Buffer.alloc(8), Buffer.alloc(36), u32(PICTURE.width << 16), u32(PICTURE.height << 16)),
    box("mdia",
      fullBox("mdhd", 1, 0, u64(3_900_000_000), u64(3_900_000_001), u32(1000), u64(3000), u16(0x55c4), u16(0)),
      fullBox("hdlr", 0, 0, u32(0), latin(spec.handler), Buffer.alloc(12), latin(`${VENDOR} handler\0`)),
      box("minf", header, box("dinf", fullBox("dref", 0, 0, u32(1), fullBox("url ", 0, 1))), stbl),
    ),
    box("udta", box("name", latin(`${VENDOR} track`))),
  );
}
function moovBox(tracks: TrackSpec[], offsets: number[][]): Buffer {
  const ilst = box("ilst", box("\xa9too", box("data", u32(1), u32(0), latin(`${VENDOR} encoder`))), box("\xa9cmt", box("data", u32(1), u32(0), latin("AI generated"))));
  return box("moov",
    fullBox("mvhd", 0, 0, u32(3_900_000_000), u32(3_900_000_001), u32(1000), u32(3000), u32(0x10000), u16(0x100), Buffer.alloc(10), Buffer.alloc(36), Buffer.alloc(24), u32(tracks.length + 1)),
    ...tracks.map((t, i) => trakBox(t, i + 1, offsets[i], offsets)),
    box("udta", fullBox("meta", 0, 0, fullBox("hdlr", 0, 0, u32(0), latin("mdir"), latin("appl"), Buffer.alloc(8), Buffer.from([0])), ilst)),
    box("uuid", Buffer.from("be7acfcb97a942e89c71999491e3afac", "hex"), latin(VENDOR_XMP)),
    box("free", latin(VENDOR)),
  );
}
/** A complete MP4: ftyp, a C2PA-style uuid box, padding, moov and mdat, with moov first or last. Sample bytes are a pattern with no text. */
const pattern = (seed: number, n: number) => { const b = Buffer.alloc(n); for (let i = 0; i < n; i++) b[i] = (seed * 31 + i * 7) & 0x7f | 0x80; return b; };
const defaultTracks = (bigVideoSample = 0): TrackSpec[] => [
  { handler: "vide", samples: [pattern(1, bigVideoSample || 301), pattern(2, 97), pattern(3, 211)], wide: false },
  { handler: "soun", samples: [pattern(4, 64), pattern(5, 65)], wide: true },
  { handler: "meta", samples: [latin(`${VENDOR} timed note`)], wide: false },
];
function mp4Fixture(moovFirst: boolean, tracks: TrackSpec[] = defaultTracks()): Buffer {
  const before = Buffer.concat([
    box("ftyp", latin("isom"), u32(0x200), latin("isomiso2avc1mp41")),
    box("uuid", C2PA_UUID, latin(`c2pa manifest store ${VENDOR}`)),
    fullBox("meta", 0, 0, fullBox("hdlr", 0, 0, u32(0), latin("mdir"), Buffer.alloc(12), latin(`${VENDOR}\0`))),
    box("free", latin(`${VENDOR} padding`)),
  ]);
  const samples = tracks.flatMap((t) => t.samples);
  const mdat = box("mdat", Buffer.concat(samples));
  const offsetsAt = (mdatStart: number) => {
    let at = mdatStart + 8;
    return tracks.map((t) => t.samples.map((s) => { const o = at; at += s.length; return o; }));
  };
  if (moovFirst) {
    const size = moovBox(tracks, offsetsAt(0)).length;
    return Buffer.concat([before, moovBox(tracks, offsetsAt(before.length + size)), mdat]);
  }
  return Buffer.concat([before, mdat, moovBox(tracks, offsetsAt(before.length)), box("skip", latin(VENDOR))]);
}

type ParsedBox = { type: string; start: number; end: number; header: number };
function boxesIn(buf: Buffer, from = 0, to = buf.length): ParsedBox[] {
  const out: ParsedBox[] = [];
  for (let pos = from; pos < to;) {
    let size = buf.readUInt32BE(pos), header = 8;
    if (size === 1) { size = Number(buf.readBigUInt64BE(pos + 8)); header = 16; }
    if (size === 0) size = to - pos;
    out.push({ type: buf.toString("latin1", pos + 4, pos + 8), start: pos, end: pos + size, header });
    pos += size;
  }
  return out;
}
const inside = (buf: Buffer, b: ParsedBox) => boxesIn(buf, b.start + b.header, b.end);
const child = (buf: Buffer, b: ParsedBox, type: string) => inside(buf, b).find((c) => c.type === type);

/** Every chunk of every track, as [handler, bytes], read through the file's own stsc, stsz and stco/co64. */
function trackChunks(buf: Buffer): { handler: string; chunks: Buffer[] }[] {
  const moov = boxesIn(buf).find((b) => b.type === "moov")!;
  return inside(buf, moov).filter((b) => b.type === "trak").map((trak) => {
    const mdia = child(buf, trak, "mdia")!, hdlr = child(buf, mdia, "hdlr")!;
    const stbl = child(buf, child(buf, mdia, "minf")!, "stbl")!;
    const handler = buf.toString("latin1", hdlr.start + 16, hdlr.start + 20);
    const stsz = child(buf, stbl, "stsz")!, stsc = child(buf, stbl, "stsc")!;
    const offsetsBox = child(buf, stbl, "stco") ?? child(buf, stbl, "co64")!;
    const wide = offsetsBox.type === "co64";
    const count = buf.readUInt32BE(offsetsBox.start + 12);
    const offsets = Array.from({ length: count }, (_, i) => wide ? Number(buf.readBigUInt64BE(offsetsBox.start + 16 + i * 8)) : buf.readUInt32BE(offsetsBox.start + 16 + i * 4));
    const fixed = buf.readUInt32BE(stsz.start + 12), sampleCount = buf.readUInt32BE(stsz.start + 16);
    const sizes = Array.from({ length: sampleCount }, (_, i) => fixed || buf.readUInt32BE(stsz.start + 20 + i * 4));
    const runs = Array.from({ length: buf.readUInt32BE(stsc.start + 12) }, (_, i) => ({ first: buf.readUInt32BE(stsc.start + 16 + i * 12), per: buf.readUInt32BE(stsc.start + 20 + i * 12) }));
    let sample = 0;
    const chunks = offsets.map((offset, index) => {
      const run = [...runs].reverse().find((r) => r.first <= index + 1)!;
      let length = 0;
      for (let k = 0; k < run.per; k++) length += sizes[sample++] ?? 0;
      return buf.subarray(offset, offset + length);
    });
    return { handler, chunks };
  });
}

function wavFixture(): Buffer {
  const chunk = (id: string, data: Buffer) => Buffer.concat([latin(id), u32le(data.length), data, data.length & 1 ? Buffer.from([0]) : Buffer.alloc(0)]);
  const pcm = Buffer.alloc(2 * 800);
  for (let i = 0; i < 800; i++) pcm.writeInt16LE(Math.round(Math.sin(i / 5) * 12000), i * 2);
  const fmt = Buffer.concat([u16le(1), u16le(1), u32le(8000), u32le(16000), u16le(2), u16le(16)]);
  const body = Buffer.concat([
    chunk("fmt ", fmt),
    chunk("LIST", Buffer.concat([latin("INFO"), chunk("ISFT", latin(`${VENDOR}\0`)), chunk("ICMT", latin("AI voice\0"))])),
    chunk("bext", latin(`${VENDOR} originator`.padEnd(256 + 32, "\0"))),
    chunk("iXML", latin(`<BWFXML><PROJECT>${VENDOR}</PROJECT></BWFXML>`)),
    chunk("id3 ", latin(`ID3 ${VENDOR}`)),
    chunk("_PMX", latin(VENDOR_XMP)),
    chunk("odd!", latin(`odd ${VENDOR}`)), // odd length: padded
    chunk("data", pcm),
    chunk("cue ", Buffer.concat([u32le(1), latin(`cue ${VENDOR}`)])),
  ]);
  return Buffer.concat([latin("RIFF"), u32le(4 + body.length), latin("WAVE"), body]);
}
function u16le(n: number) { const b = Buffer.alloc(2); b.writeUInt16LE(n); return b; }
function wavChunks(buf: Buffer) {
  const out: { id: string; data: Buffer }[] = [];
  for (let pos = 12; pos + 8 <= buf.length;) {
    const id = buf.toString("latin1", pos, pos + 4), size = buf.readUInt32LE(pos + 4);
    out.push({ id, data: buf.subarray(pos + 8, pos + 8 + size) });
    pos += 8 + size + (size & 1);
  }
  return out;
}

