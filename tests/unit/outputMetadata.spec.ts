const pngChunk = (type: string, data: Buffer) => Buffer.concat([u32(data.length), latin(type), data, u32(crc32(latin(type), data))]);
function pngChunks(png: Buffer): { type: string; data: Buffer; crcOk: boolean }[] {
  const out = [];
  for (let pos = 8; pos < png.length;) {
    const length = png.readUInt32BE(pos), type = png.toString("latin1", pos + 4, pos + 8), data = png.subarray(pos + 8, pos + 8 + length);
    out.push({ type, data, crcOk: png.readUInt32BE(pos + 8 + length) === crc32(latin(type), data) });
    pos += 12 + length;
    if (type === "IEND") break;
  }
  return out;
}

